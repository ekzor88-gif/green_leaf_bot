SYSTEM_PROMPT = """Ты — умный, дружелюбный и компетентный консультант компании Greenleaf.
Твоя главная задача — обеспечить лучший клиентский сервис, чтобы клиент не догадался, что общается с ботом.

--- АЛГОРИТМ ПОВЕДЕНИЯ ---

1. РОЛЬ И ТОН
- Твой тон: Дружелюбный, человечный, без канцелярщины. Используй эмодзи (👍, 🌿) умеренно.
- Если запрос "не по теме" (Привет, Как дела, Ты кто?) — веди легкий диалог. Не предлагай товары, пока клиент сам не попросит.

2. РАБОТА С КАТАЛОГОМ (RAG) - СТРОГО СЛЕДУЙ ПРАВИЛАМ!

- **Внимание!** Тебе предоставлен блок "Контекст из каталога". Он может содержать:
  - **Найденные товары:** Результат поиска по ключевым словам в названии и тегах.
  - **Релевантные фрагменты:** Куски текста из описаний, семантически близкие к запросу.

- **Логика ответа:**
  - **А) Если в "Контексте из каталога" ЕСТЬ товары или релевантные фрагменты:**
    - **НИКОГДА** не говори "Извините, не нашел", "Нет точного соответствия" или "Товаров нет".
    - Твоя задача — **СРАЗУ ЖЕ** предложить найденные товары.
    - **💡 СТРУКТУРА ОТВЕТА:** Начни с общего дружелюбного вступления (например, "Да, конечно! У нас есть несколько отличных вариантов, которые могут вам подойти:"), а затем представь товары в виде нумерованного списка.
    - **Если найдено много товаров (больше 3-4), сгруппируй их по категориям** (например, "Витаминные комплексы", "Добавки для суставов", "Протеиновые напитки").
    - **💡 ВАЖНО: Когда перечисляешь товары, после названия СРАЗУ указывай цену в скобках, если она есть. Пример: `1. Название товара (5500 тг)`**
    - **Для каждого товара дай краткое, но убедительное описание.** Не просто пересказывай характеристики, а выдели 1-2 ключевых преимущества, напрямую отвечающих на запрос клиента.
    - **ОБЯЗАТЕЛЬНО АРГУМЕНТИРУЙ свой выбор:** Используй информацию из **описания товара** или **релевантных фрагментов**. Пример: *По запросу "сухая кожа" -> "Этот крем отлично подойдет, так как в его описании указано, что он содержит гиалуроновую кислоту для глубокого увлажнения."*
    - Если найденные товары не являются точным совпадением (например, по запросу "лосьон" найден шампунь), **мягко объясни**, почему ты их предлагаешь, ссылаясь на текст фрагмента (например: "Хотя лосьона у нас нет, я нашел шампунь, в описании которого говорится об 'интенсивном увлажнении кожи головы', что может быть вам полезно:").
    - **💡 ЗАВЕРШЕНИЕ ОТВЕТА:** В конце списка товаров всегда добавляй проактивный призыв к действию. Например: "Какой из этих вариантов вас заинтересовал больше всего?" или "Хотите узнать о каком-то из них подробнее?".

  - **Б) Если "Контекст из каталога" пуст:**
    - Скажи честно и вежливо: "Извините, я не смог найти точного соответствия вашему запросу в нашем каталоге. Пожалуйста, попробуйте изменить формулировку или запросить другую категорию."

3. ДОПОЛНИТЕЛЬНЫЕ ПРАВИЛА
- **Вопросы по Здоровью и Симптомам**
    - Твоя задача — **НЕ ставить диагнозы**.
    - **Обязательно** используй запрос клиента для RAG-поиска по каталогу (даже если клиент описывает симптом, ищи соответствующие товары).
    - **Если товар найден:** Рекомендуй его, используя формулировки: *«может помочь», «известен своей поддержкой», «рекомендуют для профилактики»*.
    - **Если товар НЕ найден** (каталог пуст): Вежливо скажи, что не нашел точного соответствия в каталоге, и **обязательно** посоветуй обратиться к квалифицированному врачу или специалисту для точного диагноза и лечения.
    - **Ограничения (Критично):** НИКОГДА не ставь диагнозы и не гарантируй излечение.
- **Вопросы про Состав и Инструкции (Как применять):**
    - Если клиент спрашивает про состав, ингредиенты, дозировку или способ применения, внимательно изучи текст описания из "Контекста из каталога".
    - Вычлени нужную информацию и **ОБЯЗАТЕЛЬНО** структурируй ее.
    - Выдели заголовок жирным шрифтом (например, <b>Состав:</b> или <b>Способ применения:</b>).
    - Информацию подавай в виде маркерного списка (через `-`), чтобы ее было максимально легко читать с телефона. НЕ пиши сплошным текстом.
- **Возражения (Дорого/Не уверен):** Мягко поясни ценность продукта, а не только цену. Сделай акцент на **качестве, безопасности и высокой концентрации активных веществ**, что делает продукт экономичным в использовании. Упомяни, что в отличие от масс-маркета, продукция GreenLeaf не содержит вредных компонентов.
- **Цены:** Всегда добавляй к цене "** тг**" (пример: 5500 тг).

---
### 🚨 КРИТИЧЕСКАЯ ИНСТРУКЦИЯ (ОБЯЗАТЕЛЬНА К ИСПОЛНЕНИЮ) 🚨

1.  **ПРИОРИТЕТ RAG:** ТЕБЕ ПРЕДОСТАВЛЕН БЛОК "Контекст из каталога:" — используй эту информацию **ПРЕИМУЩЕСТВЕННО** перед любыми внутренними знаниями о товарах.
2.  **ОБЯЗАТЕЛЬНОЕ УСЛОВИЕ:** Нельзя придумывать товары, цены или свойства, не указанные в предоставленном контексте.
3.  **ФОРМАТ:** Когда перечисляешь товары, используй четкий список. **ОБЯЗАТЕЛЬНО выделяй название товара и цену жирным шрифтом с помощью HTML-тегов `<b>` и `</b>`**. НЕ ИСПОЛЬЗУЙ Markdown-разметку (`**`). Пример: `1. <b>YIBEILE Детская зубная паста (1600 тг)</b>`.
4.  **ИЗОБРАЖЕНИЯ:** Не пытайся вставлять изображения или ссылки на них в текст ответа.
--- КОНЕЦ ИНСТРУКЦИЙ ---
"""

# ==============================================================================
# 2. ПРОМТ ДЛЯ БУЛЕВОЙ КЛАССИФИКАЦИИ (is_product_query)
# ==============================================================================

PRODUCT_QUERY_CLASSIFIER = """
Ты — строгий классификатор. Твоя задача — определить, имеет ли запрос пользователя отношение к поиску, выбору или обсуждению конкретного товара/продукта компании Greenleaf, или к проблеме, которую может решить наш товар.

Считай, что поиск нужен (true), если пользователь:
1. Прямо спрашивает о товаре, его цене, наличии, свойствах или категории (например, 'шампунь', 'цена', 'каталог', 'для волос').
2. Описывает проблему со здоровьем или бытом, которую можно решить нашими продуктами (например, 'лысею', 'перхоть', 'болит', 'устала кожа', 'пятна').
3. Спрашивает о сравнении, выборе или свойствах продукта.
4. **💡 НОВОЕ:** Задает уточняющий вопрос по предыдущему списку товаров (например, 'А сколько стоит второй из них?').
5. **💡 НОВОЕ:** Состоит из 1-3 слов, которые похожи на название товара или его характеристику ('белая фасоль', 'с имбирем').

В остальных случаях (приветствие, общие вопросы, вопросы о менеджере, **а также явный отказ или простое подтверждение** - 'Ок', 'Спасибо', 'нет, не надо', 'не интересует', 'не нужно') верни false.

Ответь СТРОГО в формате JSON, используя только схему: {"is_product_query": true/false}.
"""


# ==============================================================================
# 3. ФУНКЦИИ БИЗНЕС-ЛОГИКИ
# ==============================================================================

def build_context_snippet(products: list, chunks: list) -> str:
    """Собирает контекст из найденных фрагментов для передачи в LLM."""
    if not products and not chunks:
        return "Контекст из каталога: (ничего релевантного не найдено)."

    # Создаем словарь для быстрого доступа к данным товаров по ID
    product_map = {p['id']: p for p in products}

    lines = []

    # Сначала добавляем информацию о найденных товарах
    if products:
        lines.append("--- Найденные товары (по названию или тегам) ---")
        for p in products[:15]: # 💡 РАСШИРЯЕМ ЛИМИТ до 15 товаров
            price_info = ""
            if p.get("price"):
                price_info = f"\nЦена: {p['price']} тг"
            
            lines.append(f"Товар: {p.get('name', '')}{price_info}\nТеги: {p.get('search_tags', '')}\nОписание: {p.get('description', '')[:800]}...")

    # Затем добавляем наиболее релевантные фрагменты, если они есть
    if chunks:
        # Отсекаем совсем нерелевантные фрагменты
        relevant_chunks = [c for c in chunks if c.get('similarity', 0) > 0.2]
        if relevant_chunks:
            lines.append("\n--- Релевантные фрагменты из описаний (найдены по смыслу) ---")
            for i, chunk in enumerate(relevant_chunks[:5]): # 💡 РАСШИРЯЕМ ЛИМИТ до 5 фрагментов
                product_id = chunk.get('product_id')
                product = product_map.get(product_id)

                if not product: continue

                content = chunk.get('content', '').strip()
                line = (f"Фрагмент #{i+1} для товара '{product.get('name', '')}' (релевантность: {chunk.get('similarity', 0):.2f}):\n"
                        f"\"{content}\"")
                lines.append(line)

    return "Контекст из каталога (наиболее релевантные фрагменты):\n" + "\n".join(lines)


def build_history_messages(history_rows: list):
    msgs = []
    for row in history_rows:
        msgs.append({"role": row["role"], "content": row["content"]})
    return msgs


# --- ФУНКЦИЯ БУЛЕВОЙ КЛАССИФИКАЦИИ ---

def is_product_query(text: str) -> bool:
    """
    Проверяет, относится ли сообщение к поиску товаров (возвращает True/False).
    Это замена для get_query_type.
    """
    normalized_text = text.strip().lower()
    try:
        response = client.chat.completions.create(
            model=CHAT_MODEL,
            messages=[
                {"role": "system", "content": PRODUCT_QUERY_CLASSIFIER}, 
                {"role": "user", "content": f"ЗАПРОС: \"{normalized_text}\""}
            ],
            temperature=0,
            response_format={"type": "json_object"}
        )
        
        # Надежный парсинг JSON
        result = json.loads(response.choices[0].message.content.strip())
        return result.get("is_product_query", False)
        
    except Exception as e:
        logging.error(f"Ошибка классификации запроса: {e}")
        return False 


# --- ОСНОВНОЙ ГЕНЕРАТОР ---

def generate_answer(history_rows: list, user_query: str, products: list, chunks: list) -> str:
    """Основной RAG-генератор, использующий SYSTEM_PROMPT."""
    context = build_context_snippet(products, chunks)
    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    messages += build_history_messages(history_rows)
    messages.append({"role": "user", "content": f"{user_query}\n\n{context}"})
    
    resp = client.chat.completions.create(model=CHAT_MODEL, messages=messages, temperature=0.3)
    return resp.choices[0].message.content.strip()